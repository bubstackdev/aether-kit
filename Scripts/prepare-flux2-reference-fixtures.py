#!/usr/bin/env python3
"""Independent float32 reference fixtures for FLUX.2 [klein]: text to image and reference-image conditioning.

Uses only the unmodified Diffusers `Flux2KleinPipeline` public call plus module hooks (no exported
Aether model and no AetherKit code), so it is independent of the Core AI bundle under test:

    uv run --frozen --project Forge python -I Scripts/prepare-flux2-reference-fixtures.py \
        [--device cpu|mps] CHECKPOINT_DIR T2I_FIXTURE_DIR OUTPUT_DIR
    uv run --frozen --project Forge python -I Scripts/prepare-flux2-reference-fixtures.py \
        [--device cpu|mps] --text-to-image CHECKPOINT_DIR OUTPUT_DIR

The references run on the CPU by default (float32, like every other model's references); `--device mps` is
kept for comparison only. The text encoder always runs on the CPU in float32. The device is recorded in the
fixture document.

Reference-image mode: reference pictures are the oracle's own text-to-image outputs from T2I_FIXTURE_DIR
(generated by the Apache-2.0 checkpoint), resized with PIL Lanczos to token multiples so the pipeline does
not resize them again. Per case it records the padded token ids/mask, float32 text rows, packed initial
noise, the exact encoder input pixels, the reference tokens appended to the transformer input, per-step
generated-token latents/timestep/velocity (teacher-forcing material), the final packed latent and the
float32 image ([H, W, 3] in [0, 1]) plus PNG.

`--text-to-image` writes the ten-case `diffusion` fixture (512² to 1344×768, including a French/Japanese
prompt) with the same per-case records, without references.

OUTPUT_DIR/fixtures/<id>/ is written; <id> hashes the document and every file, as Forge's diffusion
fixtures do.
"""

from __future__ import annotations

import argparse
import gc
import hashlib
import io
import json
from importlib.metadata import version
from pathlib import Path

import numpy as np
import torch

STEPS = 4
CASES = [
    {"id": "fox-watercolor-ref1", "prompt": "Turn this photo into a loose watercolor painting with visible paper texture",
     "width": 512, "height": 512, "seed": 11512, "references": [("fox-512", 256, 256)]},
    {"id": "fox-lighthouse-ref2", "prompt": "The red fox from the first picture sitting on the rocks in front of the lighthouse from the second picture",
     "width": 512, "height": 384, "seed": 12384, "references": [("fox-512", 256, 256), ("lighthouse-512", 192, 256)]},
]
T2I_CASES = [
    {"id": "lighthouse-512", "prompt": "A lighthouse at dusk, watercolor", "width": 512, "height": 512, "seed": 1512},
    {"id": "red-circle-512", "prompt": "A red circle on a white background", "width": 512, "height": 512, "seed": 2512},
    {"id": "fox-512", "prompt": "A red fox standing in fresh snow at sunrise, telephoto wildlife photograph",
     "width": 512, "height": 512, "seed": 3512},
    {"id": "ramen-576x448", "prompt": "A bowl of ramen on a wooden table, overhead photo", "width": 576, "height": 448, "seed": 4576},
    {"id": "cafe-512", "prompt": "Un café sur une table en bois, lumière du matin — 東京の夜景", "width": 512, "height": 512, "seed": 5512},
    {"id": "cat-1024", "prompt": "Close-up photo of a tabby cat wearing tiny round glasses, sitting on a stack of old books in a "
     "sunlit library, shallow depth of field, warm tones", "width": 1024, "height": 1024, "seed": 61024},
    {"id": "harbor-768", "prompt": "A small fishing harbor at golden hour, boats with colorful hulls, gentle ripples, photograph",
     "width": 768, "height": 768, "seed": 7768},
    {"id": "street-1024x576", "prompt": "A rainy city street at night with neon signs reflected on wet asphalt, cinematic wide shot",
     "width": 1024, "height": 576, "seed": 81024},
    {"id": "desk-1024x768", "prompt": "A tidy wooden writing desk by a window with a brass lamp, an open notebook and a mug of tea, "
     "soft morning light", "width": 1024, "height": 768, "seed": 91024},
    {"id": "canyon-1344x768", "prompt": "A wide desert canyon at sunset with layered red rock walls and a winding river, panoramic "
     "landscape photograph", "width": 1344, "height": 768, "seed": 101344},
]


def canonical(obj) -> str:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def main(checkpoint: Path, t2i: Path | None, out: Path, dev: torch.device) -> None:
    from diffusers import Flux2KleinPipeline
    from PIL import Image
    from transformers import AutoTokenizer, Qwen3ForCausalLM

    cases = T2I_CASES if t2i is None else CASES
    tok = AutoTokenizer.from_pretrained(checkpoint / "tokenizer")
    t2i_cases = {} if t2i is None else {
        json.loads(l)["id"]: json.loads(l) for l in (t2i / "cases.jsonl").read_text().splitlines() if l.strip()}

    # 1. Token ids, mask and float32 text rows (CPU, the reference text encoder in float32).
    rows: dict[str, dict[str, np.ndarray]] = {}
    for c in cases:
        text = tok.apply_chat_template([{"role": "user", "content": c["prompt"]}], tokenize=False,
                                       add_generation_prompt=True, enable_thinking=False)
        enc = tok(text, return_tensors="np", padding="max_length", truncation=True, max_length=512)
        rows[c["id"]] = {"ids": enc["input_ids"][0].astype(np.int32), "mask": enc["attention_mask"][0].astype(np.int32)}
    encoder = Qwen3ForCausalLM.from_pretrained(checkpoint / "text_encoder", torch_dtype=torch.float32).eval()
    with torch.no_grad():
        for c in cases:
            emb = Flux2KleinPipeline._get_qwen3_prompt_embeds(encoder, tok, c["prompt"], dtype=torch.float32,
                                                               device=torch.device("cpu"))
            rows[c["id"]]["text"] = emb[0].float().numpy()
    del encoder
    gc.collect()

    # 2. Float32 generations (with references in reference-image mode), recording every transformer call and encoder input.
    pipe = Flux2KleinPipeline.from_pretrained(checkpoint, text_encoder=None, tokenizer=None,
                                              torch_dtype=torch.float32).to(dev)
    calls: list[dict[str, np.ndarray]] = []
    encoded_pixels: list[np.ndarray] = []

    def hook(_m, _args, kwargs, out_):
        calls.append({"hidden": kwargs["hidden_states"][0].float().cpu().numpy().copy(),
                      "timestep": kwargs["timestep"].float().cpu().numpy().copy(),
                      "img_ids": kwargs["img_ids"][0].cpu().numpy().copy() if kwargs["img_ids"].dim() == 3
                      else kwargs["img_ids"].cpu().numpy().copy(),
                      "velocity": (out_[0] if isinstance(out_, tuple) else out_.sample)[0].float().cpu().numpy().copy()})

    handle = pipe.transformer.register_forward_hook(hook, with_kwargs=True)
    original_encode = pipe.vae.encode

    def encode(x, *args, **kwargs):
        encoded_pixels.append(x[0].float().cpu().numpy().copy())
        return original_encode(x, *args, **kwargs)

    pipe.vae.encode = encode
    files: dict[str, bytes] = {}
    expected = []
    for c in cases:
        calls.clear()
        encoded_pixels.clear()
        h, w = c["height"] // 16, c["width"] // 16
        references = c.get("references", [])
        refs = []
        for source, rw, rh in references:
            image = Image.open(t2i / t2i_cases[source]["files"]["png"]).convert("RGB")
            refs.append(image.resize((rw, rh), Image.Resampling.LANCZOS))
        g = torch.Generator().manual_seed(int(c["seed"]))
        noise = torch.randn((1, 128, h, w), generator=g, dtype=torch.float32)
        ends: list[np.ndarray] = []

        def on_end(_p, _i, _t, kw):
            ends.append(kw["latents"][0].float().cpu().numpy().copy())
            return {}

        emb = torch.from_numpy(rows[c["id"]]["text"])[None].to(dev, torch.float32)
        with torch.no_grad():
            img = pipe(prompt_embeds=emb, image=refs or None, height=c["height"], width=c["width"], num_inference_steps=STEPS,
                       guidance_scale=1.0, latents=noise.to(dev), output_type="np", callback_on_step_end=on_end,
                       callback_on_step_end_tensor_inputs=["latents"]).images[0]
        n = h * w
        ref_tokens = sum((rh // 16) * (rw // 16) for _, rw, rh in references)
        assert len(calls) == STEPS, len(calls)
        assert len(encoded_pixels) == len(refs), len(encoded_pixels)
        assert all(x["hidden"].shape == (n + ref_tokens, 128) for x in calls), [x["hidden"].shape for x in calls]
        packed_noise = noise.reshape(128, n).T.contiguous().numpy()
        assert np.array_equal(calls[0]["hidden"][:n], packed_noise), "pipeline packing differs from [tokens,128] noise"
        base = f"cases/{c['id']}"
        f = {"ids": f"{base}/ids.i32", "mask": f"{base}/mask.i32", "text": f"{base}/text.f32", "noise": f"{base}/noise.f32",
             "final": f"{base}/final.f32", "image": f"{base}/image.f32", "png": f"{base}/image.png",
             "stepLatents": [f"{base}/step{i}.latents.f32" for i in range(STEPS)],
             "stepVelocities": [f"{base}/step{i}.velocity.f32" for i in range(STEPS)]}
        if references:
            f |= {"referenceLatents": f"{base}/reference-latents.f32", "positions": f"{base}/positions.i32",
                  "referencePixels": [f"{base}/reference{k}.pixels.f32" for k in range(len(refs))],
                  "referencePNGs": [f"{base}/reference{k}.png" for k in range(len(refs))]}
            reference_latents = calls[0]["hidden"][n:]
            assert all(np.array_equal(x["hidden"][n:], reference_latents) for x in calls), "reference tokens changed"
            files[f["referenceLatents"]] = reference_latents.astype("<f4").tobytes()
            files[f["positions"]] = calls[0]["img_ids"].astype("<i4").tobytes()
            for k, (pixels, picture) in enumerate(zip(encoded_pixels, refs)):
                files[f["referencePixels"][k]] = pixels.astype("<f4").tobytes()
                buffer = io.BytesIO()
                picture.save(buffer, format="PNG")
                files[f["referencePNGs"][k]] = buffer.getvalue()
        r = rows[c["id"]]
        files[f["ids"]] = r["ids"].astype("<i4").tobytes()
        files[f["mask"]] = r["mask"].astype("<i4").tobytes()
        files[f["text"]] = r["text"].astype("<f4").tobytes()
        files[f["noise"]] = packed_noise.astype("<f4").tobytes()
        files[f["final"]] = ends[-1].astype("<f4").tobytes()
        files[f["image"]] = img.astype("<f4").tobytes()
        png = io.BytesIO()
        Image.fromarray((np.clip(img, 0, 1) * 255).round().astype(np.uint8)).save(png, format="PNG")
        files[f["png"]] = png.getvalue()
        for i, call in enumerate(calls):
            files[f["stepLatents"][i]] = call["hidden"][:n].astype("<f4").tobytes()
            files[f["stepVelocities"][i]] = call["velocity"][:n].astype("<f4").tobytes()
        record = {"id": c["id"], "prompt": c["prompt"], "width": c["width"], "height": c["height"],
                  "seed": c["seed"], "steps": STEPS, "realTokens": int(r["mask"].sum()),
                  "timesteps": [float(x["timestep"].reshape(-1)[0]) for x in calls], "files": f}
        if references:
            record |= {"references": [{"source": s, "width": rw, "height": rh} for s, rw, rh in references],
                       "referenceTokens": ref_tokens}
        else:
            record["textShape"] = list(r["text"].shape)
        expected.append(record)
        print(c["id"], "tokens", n, "+", ref_tokens, flush=True)
    handle.remove()
    files["cases.jsonl"] = "".join(canonical(e) + "\n" for e in expected).encode()
    oracle = {"torch": version("torch"), "diffusers": version("diffusers"), "transformers": version("transformers"),
              "dtype": "float32", "device": dev.type, "textEncoderDevice": "cpu", "threads": torch.get_num_threads(),
              "steps": STEPS, "noise": "torch.Generator(seed).randn, packed"}
    fixture = {"schema": 1, "source": {"hfRepo": "black-forest-labs/FLUX.2-klein-4B", "revision": checkpoint.name},
               "cases": "cases.jsonl",
               "sha256": {name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())}}
    if t2i is None:
        fixture |= {"kind": "diffusion", "recipe": "flux2-klein-4b-reference@1", "oracle": oracle | {"pipeline": "Flux2KleinPipeline"}}
    else:
        fixture |= {"kind": "flux2-reference-images", "oracle": oracle | {"pipeline": "Flux2KleinPipeline(image=[PIL...])"},
                    "referenceSource": {"t2iFixture": t2i.name, "resize": "PIL LANCZOS"}}
    digest = hashlib.sha256(canonical(fixture).encode())
    for name in sorted(files):
        digest.update(files[name])
    fixture_id = digest.hexdigest()[:16]
    target = out / "fixtures" / fixture_id
    target.mkdir(parents=True, exist_ok=False)
    for name, data in files.items():
        (target / name).parent.mkdir(parents=True, exist_ok=True)
        (target / name).write_bytes(data)
    (target / "fixture.json").write_text(json.dumps({"id": fixture_id, **fixture}, indent=2, sort_keys=True,
                                                    ensure_ascii=False) + "\n")
    print("AETHER_FIXTURE", target, flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--device", choices=["cpu", "mps"], default="cpu",
                        help="pipeline device (default cpu; the text encoder always runs on the CPU)")
    parser.add_argument("--text-to-image", action="store_true", help="write the ten-case text-to-image fixture")
    parser.add_argument("paths", nargs="+", metavar="PATH")
    args = parser.parse_args()
    if len(args.paths) != (2 if args.text_to_image else 3):
        parser.error("expected CHECKPOINT_DIR OUTPUT_DIR with --text-to-image, else CHECKPOINT_DIR T2I_FIXTURE_DIR OUTPUT_DIR")
    paths = [Path(p).resolve() for p in args.paths]
    if args.device == "mps" and not torch.backends.mps.is_available():
        raise SystemExit("--device mps requested but MPS is not available")
    main(paths[0], None if args.text_to_image else paths[1], paths[-1], torch.device(args.device))
